@transaction.atomic
def run():
    print("[*] Clearing and building comprehensive vehicle database...")
    # Optional: clean existing CarModel and CarMake or get_or_create
    total_makes = 0
    total_models = 0

    for make_name, models in car_database.items():
        make_obj, _ = CarMake.objects.get_or_create(name=make_name)
        total_makes += 1
        for model_tuple in models:
            m_name, y_from, y_to, eng, chassis = model_tuple
            cm_obj, created = CarModel.objects.get_or_create(
                make=make_obj,
                name=m_name,
                year_from=y_from,
                year_to=y_to,
                defaults={
                    "engine_type": eng,
                    "chassis_prefixes": chassis
                }
            )
            if not created:
                cm_obj.engine_type = eng
                cm_obj.chassis_prefixes = chassis
                cm_obj.save()
            total_models += 1

    print(f"[+] Successfully loaded {total_makes} Car Makes and {total_models} Car Models into the database!")

if __name__ == '__main__':
    run()
